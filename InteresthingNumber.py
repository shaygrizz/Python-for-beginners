# Задача: «Интересное число»
# Дано натуральное трёхзначное число.
# Число интересное, если (максимальная цифра - минимальная цифра) == средней по величине цифре.
# Если число интересное, вывести «Число интересное», иначе «Число неинтересное».

print('Введите трёхзначное число:')
n = int(input())

# Достаём цифры
a = n // 100        # сотни
b = n // 10 % 10    # десятки
c = n % 10          # единицы

# Максимум, минимум и средняя цифра
maximum = max(a, b, c)
minimum = min(a, b, c)
middle = a + b + c - maximum - minimum

# Проверяем условие
if maximum - minimum == middle:
    print('Число интересное')
else:
    print('Число неинтересное')