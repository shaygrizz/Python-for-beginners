# Задача: «Палиндром»
# Дано трёхзначное число.
# Число - палиндром, если читается одинаково слева направо и справа налево.
# Если палиндром, вывести «Палиндром», иначе «Не палиндром».


n = int(input())

a = n // 100    # сотни
c = n % 10      # единицы

if a == c:
    print('Палиндром')
else:
    print('Не палиндром')